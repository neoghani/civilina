<?php

declare(strict_types=1);

/*
 * Local preview of civilina.com, laid out like the server:
 *
 *   php -S 127.0.0.1:8765 -t site-vitrine app/tools/dev-router.php
 *
 * - Static pages and assets come from site-vitrine/ (the document root).
 * - PHP pages (/login/, /register/, /logout/, /dashboard/, /admin/,
 *   /entreprise/) come from app/public/, as they do in public_html.
 * - Private code is loaded from app/private/ through small stubs in
 *   <repo>/civilina_private/, which also holds the local data (users,
 *   contacts, SQLite). That folder is git-ignored and created on first use.
 * - Unknown paths get a real 404 instead of the homepage (whose relative
 *   asset links would break under another path).
 */

$repo = dirname(__DIR__, 2);
// Next to the served document root, as on the server (repo: <repo>/civilina_private).
$privateDir = dirname(rtrim((string) $_SERVER['DOCUMENT_ROOT'], '/\\')) . '/civilina_private';
putenv('CIVILINA_PRIVATE_DIR=' . $privateDir);
// E-mails are written to <private>/outbox instead of being sent (civilina_newsletter.php).
putenv('CIVILINA_MAIL_OUTBOX=' . $privateDir . '/outbox');

civilina_dev_prepare_private_dir($repo, $privateDir);

$path = (string) (parse_url((string) ($_SERVER['REQUEST_URI'] ?? '/'), PHP_URL_PATH) ?: '/');

// PHP pages of the app.
if (preg_match('~^/([a-z-]+)/?(index\.php)?$~', $path, $match)) {
    $page = $repo . '/app/public/' . $match[1] . '/index.php';
    if (is_file($page)) {
        if (!str_ends_with($path, '/') && ($match[2] ?? '') === '') {
            header('Location: ' . $path . '/' . (($q = parse_url((string) $_SERVER['REQUEST_URI'], PHP_URL_QUERY)) ? '?' . $q : ''), true, 301);
            return true;
        }
        $_SERVER['SCRIPT_FILENAME'] = $page;
        $_SERVER['SCRIPT_NAME'] = $_SERVER['PHP_SELF'] = '/' . $match[1] . '/index.php';
        chdir(dirname($page));
        require $page;
        return true;
    }
}

// Static files and directory indexes of the site.
$target = rtrim((string) $_SERVER['DOCUMENT_ROOT'], '/\\') . $path;
if (is_file($target)) {
    return false;
}
if (is_dir($target) && (is_file($target . '/index.html') || is_file($target . '/index.php'))) {
    if (!str_ends_with($path, '/')) {
        header('Location: ' . $path . '/', true, 301);
        return true;
    }
    return false;
}

http_response_code(404);
header('Content-Type: text/html; charset=utf-8');
echo '<!doctype html><meta charset="utf-8"><title>404 | Civilina (local)</title>'
    . '<link rel="stylesheet" href="/assets/css/site.css">'
    . '<main class="shell" style="padding:80px 0"><h1>Page introuvable</h1>'
    . '<p class="lead">Ce chemin n\'existe pas dans l\'aperçu local : ' . htmlspecialchars($path, ENT_QUOTES, 'UTF-8') . '</p>'
    . '<p style="margin-top:1.5rem"><a class="btn btn-primary" href="/">Retour à l\'accueil</a></p></main>';
return true;

/** Stubs that load the versioned code from app/private, as ~/civilina_private does on the server. */
function civilina_dev_prepare_private_dir(string $repo, string $dir): void
{
    if (!is_dir($dir)) {
        mkdir($dir, 0700, true);
    }

    foreach (['civilina_auth.php', 'civilina_admin.php', 'civilina_db.php', 'civilina_journal.php', 'civilina_stats.php', 'civilina_markup.php', 'civilina_articles.php', 'civilina_publish.php', 'civilina_admin_journal.php', 'civilina_newsletter.php', 'civilina_admin_newsletter.php', 'civilina_seo.php', 'civilina_sales.php', 'civilina_admin_sales.php', 'civilina_content.php'] as $file) {
        $stub = $dir . '/' . $file;
        $source = $repo . '/app/private/' . $file;
        if (!is_file($stub) && is_file($source)) {
            file_put_contents($stub, "<?php\n// Local dev stub (generated by app/tools/dev-router.php).\nrequire_once " . var_export($source, true) . ";\n");
        }
    }

    // The MBTI module lives only on the server: a neutral stand-in keeps /dashboard/ working locally.
    $mbti = $dir . '/mbti_module.php';
    if (!is_file($mbti)) {
        file_put_contents($mbti, <<<'PHP'
<?php
// Local dev stand-in for the server-only MBTI module.
function civilina_mbti_latest_for_user(array $user): ?array { return null; }
function civilina_mbti_result_url(string $locale, string $sessionId): string { return '#'; }
PHP);
    }
}
